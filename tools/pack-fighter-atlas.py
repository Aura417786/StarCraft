"""Pack Blender's five camera-aligned poses per craft into browser WebP atlases."""

import argparse
import json
from pathlib import Path

from PIL import Image


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("frames", type=Path)
    parser.add_argument("output", type=Path, help="Project root containing assets/fighters")
    args = parser.parse_args()
    poses = json.loads((args.frames / "fighter-frames.json").read_text(encoding="utf-8"))
    folder = args.output / "assets" / "fighters" / "atlas"
    folder.mkdir(parents=True, exist_ok=True)
    catalog = {}
    for id_, frames in poses.items():
        if len(frames) != 5:
            raise ValueError(f"{id_} must have five rendered poses")
        images = [Image.open(args.frames / frame["file"]).convert("RGBA") for frame in frames]
        width, height = images[0].size
        sheet = Image.new("RGBA", (width * len(images), height))
        max_width, max_height = 0, 0
        metadata = []
        for index, (frame, image) in enumerate(zip(frames, images)):
            if image.size != (width, height):
                raise ValueError(f"Pose dimensions differ for {id_}")
            solid = image.getchannel("A").point(lambda alpha: 255 if alpha >= 96 else 0)
            bounds = solid.getbbox()
            if not bounds or min(bounds[0], bounds[1], width - bounds[2], height - bounds[3]) < 6:
                raise ValueError(f"{id_} frame {index} is empty or clipped: {bounds}")
            muzzle_x, muzzle_y = frame["nose"][0] * width, frame["nose"][1] * height
            if not (abs(muzzle_x - bounds[2]) <= 8 and bounds[1] < muzzle_y < bounds[3]):
                raise ValueError(f"{id_} frame {index} has a visibly offset nose: {frame['nose']}, {bounds}")
            max_width = max(max_width, muzzle_x - bounds[0])
            max_height = max(max_height, abs(bounds[1] - muzzle_y) * 2, abs(bounds[3] - muzzle_y) * 2)
            metadata.append({key: frame[key] for key in ("nose", "engines", "reflections")})
            sheet.paste(image, (width * index, 0))
        sheet.save(folder / (id_ + ".webp"), quality=91, method=6, exact=True)
        catalog[id_] = {"width": width, "height": height, "bodyWidth": round(max_width, 2),
                        "bodyHeight": round(max_height, 2), "frames": metadata}
    target = args.output / "fighter-atlas-data.js"
    target.write_text('"use strict";\n\n// Generated by tools/pack-fighter-atlas.py.\nconst fighterAtlasCatalog = '
                      + json.dumps(catalog, indent=2) + ";\n", encoding="utf-8")
    print(f"Packed {len(catalog)} atlases to {folder}")


if __name__ == "__main__":
    main()
