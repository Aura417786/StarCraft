"""Pack Blender's five camera-aligned poses per craft into browser WebP atlases."""

import argparse
import json
from pathlib import Path

from PIL import Image


def pack_kestrel_neutral(image, solid, pose, folder, id_):
    """Share the middle atlas pose with the low-quality, opening and hangar paths."""
    width, height = image.size
    bounds = solid.getbbox()
    left, top = max(0, bounds[0] - 5), max(0, bounds[1] - 5)
    right, bottom = min(width, bounds[2] + 5), min(height, bounds[3] + 5)
    art = image.crop((left, top, right, bottom))
    art.save(folder / f"{id_}.webp", quality=93, method=6, exact=True)

    def translate(point):
        return [round(point[0] * width - left, 3), round(point[1] * height - top, 3)]

    return {"src": f"assets/fighters/kestrel/{id_}.webp",
            "crop": [0, 0, art.width, art.height],
            "tip": translate(pose["nose"]),
            "engines": [translate(point) for point in pose["engines"]],
            "reflections": [{"side": side, "weight": .59,
                             "points": [translate(point) for point in path]}
                            for side, path in zip((-1, 1), pose["reflections"])]}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("frames", type=Path)
    parser.add_argument("output", type=Path, help="Project root containing assets/fighters")
    parser.add_argument("--kestrel", action="store_true", help="Also pack the three neutral Kestrel portraits")
    args = parser.parse_args()
    poses = json.loads((args.frames / "fighter-frames.json").read_text(encoding="utf-8"))
    folder = args.output / "assets" / "fighters" / "atlas"
    folder.mkdir(parents=True, exist_ok=True)
    neutral_folder = folder.parent / "kestrel"
    if args.kestrel:
        if set(poses) != {"red", "blue", "yellow"}:
            raise ValueError("Kestrel release must contain all three fighters")
        neutral_folder.mkdir(parents=True, exist_ok=True)
    catalog = {}
    for id_, frames in poses.items():
        if len(frames) != 5:
            raise ValueError(f"{id_} must have five rendered poses")
        images = [Image.open(args.frames / frame["file"]).convert("RGBA") for frame in frames]
        width, height = images[0].size
        sheet = Image.new("RGBA", (width * len(images), height))
        max_width, max_height = 0, 0
        metadata = []
        neutral = None
        for index, (frame, image) in enumerate(zip(frames, images)):
            if image.size != (width, height):
                raise ValueError(f"Pose dimensions differ for {id_}")
            solid = image.getchannel("A").point(lambda alpha: 255 if alpha >= 96 else 0)
            bounds = solid.getbbox()
            if not bounds or min(bounds[0], bounds[1], width - bounds[2], height - bounds[3]) < 6:
                raise ValueError(f"{id_} frame {index} is empty or clipped: {bounds}")
            muzzle_x, muzzle_y = frame["nose"][0] * width, frame["nose"][1] * height
            if args.kestrel:
                # The fork outriggers can extend in front of the center gun.
                x, y = round(muzzle_x), round(muzzle_y)
                valid_muzzle = (bounds[0] < x <= bounds[2] + 2 and bounds[1] < y < bounds[3]
                                and solid.crop((x - 8, y - 8, x + 9, y + 9)).getbbox())
                frame_width = bounds[2] - bounds[0]
            else:
                valid_muzzle = abs(muzzle_x - bounds[2]) <= 8 and bounds[1] < muzzle_y < bounds[3]
                frame_width = muzzle_x - bounds[0]
            if not valid_muzzle:
                raise ValueError(f"{id_} frame {index} has a visibly offset nose: {frame['nose']}, {bounds}")
            max_width = max(max_width, frame_width)
            max_height = max(max_height, abs(bounds[1] - muzzle_y) * 2, abs(bounds[3] - muzzle_y) * 2)
            metadata.append({key: frame[key] for key in ("nose", "engines", "reflections")})
            sheet.paste(image, (width * index, 0))
            if args.kestrel and index == 2:
                neutral = pack_kestrel_neutral(image, solid, frame, neutral_folder, id_)
        sheet.save(folder / (id_ + ".webp"), quality=91, method=6, exact=True)
        catalog[id_] = {"width": width, "height": height, "bodyWidth": round(max_width, 2),
                        "bodyHeight": round(max_height, 2), "frames": metadata}
        if neutral:
            catalog[id_]["fallback"] = neutral
    target = args.output / "fighter-atlas-data.js"
    target.write_text('"use strict";\n\n// Generated by tools/pack-fighter-atlas.py.\nconst fighterAtlasCatalog = '
                      + json.dumps(catalog, indent=2) + ";\n", encoding="utf-8")
    print(f"Packed {len(catalog)} atlases to {folder}")


if __name__ == "__main__":
    main()
