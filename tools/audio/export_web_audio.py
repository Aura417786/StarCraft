"""Export the existing Opus bank for HTTP playback without re-encoding."""

import base64
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "assets" / "audio"


def read_bank(filename, symbol):
    text = (ROOT / filename).read_text(encoding="utf-8")
    return json.loads(text.split(f"const {symbol} = ", 1)[1].strip().removesuffix(";"))


def save_ogg(name, encoded):
    payload = base64.b64decode(encoded, validate=True)
    if not payload.startswith(b"OggS") or b"OpusHead" not in payload[:64]:
        raise ValueError(f"{name} is not an Ogg Opus clip")
    (OUTPUT / f"{name}.ogg").write_bytes(payload)


def main():
    base = read_bank("audio-bank.js", "starBreakerAudioBank")
    factions = read_bank("audio-faction-bank.js", "starBreakerFactionAudio")
    OUTPUT.mkdir(parents=True, exist_ok=True)
    catalog = {"stems": {}, "effects": list(base["effects"]), "factions": {}}
    for name, (duration, encoded) in base["stems"].items():
        catalog["stems"][name] = duration
        save_ogg(name, encoded)
    for name, encoded in base["effects"].items():
        save_ogg(name, encoded)
    for faction, profile in factions["factions"].items():
        catalog["factions"][faction] = {key: value for key, value in profile.items() if key != "layers"}
        layers = catalog["factions"][faction]["layers"] = {}
        for layer, (duration, encoded) in profile["layers"].items():
            layers[layer] = duration
            save_ogg(f"{faction}_{layer}", encoded)
    save_ogg("victory", factions["victory"][1])
    (ROOT / "audio-catalog.js").write_text(
        '"use strict";\n// Generated by tools/audio/export_web_audio.py. See assets/audio-LICENSE.md.\n'
        f"const starBreakerAudioCatalog = {json.dumps(catalog, indent=2)};\n", encoding="utf-8"
    )


if __name__ == "__main__":
    main()
